test('feed mantém página carregada quando carregar mais falha e reinicia ao atualizar', async ({ page, request }) => {
  const autor = await pessoa(request), leitor = await pessoa(request);
  for (let i = 0; i < 12; i++) expect((await request.post(`${back}/posts`, { headers: autor.headers, data: { texto: `Texto ${i}` } })).status()).toBe(201);
  await request.post(`${back}/usuarios/${autor.username}/follow`, { headers: leitor.headers });
  await page.goto('/login');
  await page.getByLabel('Usuário', { exact: true }).fill(leitor.username);
  await page.getByLabel('Senha', { exact: true }).fill(senha);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.getByRole('link', { name: 'Feed', exact: true }).click();
  await expect(page.getByRole('article')).toHaveCount(10);
  await page.route('**/feed?offset=10&limit=10', route => route.fulfill({ status: 500, body: '{}' }));
  await page.getByRole('button', { name: 'Carregar mais' }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'indisponível' })).toBeVisible();
  await expect(page.getByRole('article')).toHaveCount(10);
  await page.unroute('**/feed?offset=10&limit=10');
  await page.getByRole('button', { name: 'Tentar novamente', exact: true }).click();
  await expect(page.getByRole('article')).toHaveCount(12);
  await page.getByRole('button', { name: 'Atualizar feed' }).click();
  await expect(page.getByRole('article')).toHaveCount(10);
  await page.goto(`/pessoas/${autor.username}`);
  await expect(page.getByRole('button', { name: 'Deixar de seguir', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Deixar de seguir', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Seguir', exact: true })).toBeVisible();
  await page.goto('/feed');
  await expect(page.getByText(/Nenhuma publicação por aqui ainda/)).toBeVisible();
});
